import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import {
  assistantOperations,
  describeSchema,
} from "../src/assistant/operations";

const root = resolve(__dirname, "../../..");

const operations = assistantOperations.map(({ schema, ...operation }) => {
  return { ...operation, inputSchema: describeSchema(schema) };
});

writeFileSync(
  resolve(root, "docs/110-assistant-api-operations.json"),
  JSON.stringify(
    {
      generatedFrom: "apps/api-ts/src/assistant/operations.ts",
      note: "Schemas document tool input. Original Zod contracts and API service rules remain authoritative, including refinements and record scopes.",
      operations,
    },
    (_key, value) => {
      return value instanceof RegExp ? value.source : value;
    },
    2,
  ) + "\n",
);

const schema = readFileSync(
  resolve(root, "apps/api-ts/prisma/schema.prisma"),
  "utf8",
);

const models = [...schema.matchAll(/^model (\w+) \{\n([\s\S]*?)^\}/gm)];

let dictionary = `# Database field dictionary\n\nGenerated by \`apps/api-ts/scripts/document-assistant.ts\` from \`apps/api-ts/prisma/schema.prisma\`. Regenerate after schema changes. This is storage documentation; a model's existence does not grant assistant access. See [Fresh AI API tools](110-fresh-ai-api-tools.md) and its operation allowlist.\n\nMoney is decimal PHP, never a float or directly editable balance. Payment dates scope payment reports; installment due dates scope scheduled earnings; task/support reports use creation dates. Client/member balances use lifetime net Finance-verified credit. Scheduled amounts are neither collections nor profit.\n\nIdentifiers are server-generated UUIDs unless specified otherwise. \`?\` means nullable, \`[]\` means a collection/relation, \`@unique\`/\`@@unique\` constrain duplicates, \`@updatedAt\` is maintained by Prisma, and \`version\` is used for optimistic concurrency. Relations are references, not permission grants. Financial and audit history uses restricted deletion. Authentication, tokens, identity documents, applicant details and confidential HR are private and are excluded from assistant tools unless an explicitly listed API provides a permitted projection. Never send password hashes, session tokens or provider keys to the model.\n\n`;

for (const [, name, body] of models) {
  dictionary += `## ${name}\n\n| Field | Type | Constraints / relation |\n| --- | --- | --- |\n`;

  for (const line of body.split("\n")) {
    const field = line.trim().match(/^(\w+)\s+(\w+(?:\[\]|\?)?)\s*(.*)$/);

    if (field) {
      dictionary += `| ${field[1]} | \`${field[2]}\` | ${field[3].replaceAll("|", "\\|") || "—"} |\n`;
    }
  }

  const constraints = body
    .split("\n")
    .map((line) => {
      return line.trim();
    })
    .filter((line) => {
      return line.startsWith("@@");
    });

  if (constraints.length) {
    dictionary +=
      "\nIndexes and constraints: " +
      constraints
        .map((line) => {
          return `\`${line}\``;
        })
        .join("; ") +
      ".\n";
  }

  dictionary += "\n";
}

dictionary += "## Enumerations\n\n";

for (const [, name, body] of schema.matchAll(
  /^enum (\w+) \{\n([\s\S]*?)^\}/gm,
)) {
  dictionary += `- **${name}**: ${body
    .split("\n")
    .map((line) => {
      return line.trim();
    })
    .filter((line) => {
      return line && !line.startsWith("//");
    })
    .join(", ")}\n`;
}

writeFileSync(resolve(root, "docs/111-data-dictionary.md"), dictionary);

console.log(
  `Documented ${operations.length} API operations and ${models.length} database models.`,
);
